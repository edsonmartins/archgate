package br.com.integralltech.archgate.orchestration.adapter;

import br.com.integralltech.archgate.orchestration.config.OrchestrationProperties;

import java.util.List;
import java.util.Map;

/**
 * OpenBao lease/policy side-effects for ephemeral DB/SSH access.
 * Live calls require ORCH_OPENBAO_ENABLED=true and token with sys/leases + policy write.
 */
public class OpenBaoLiveAdapter extends HttpLiveAdapter {

  public OpenBaoLiveAdapter(OrchestrationProperties.Endpoint endpoint, boolean dryRun) {
    super(endpoint, dryRun);
  }

  @Override
  public String name() {
    return "openbao";
  }

  @Override
  public void ensurePerson(String username, String email, List<String> groups) {
    // Optional: entity alias — deferred; identity is ArchGuard.
  }

  @Override
  public void grantAccess(String username, String target, String ttl) {
    String policyName = "archgate-" + encode(username);
    String policy = """
        # Generated by archgate-orchestration for %s target=%s ttl=%s
        path "database/creds/*" {
          capabilities = ["read"]
        }
        path "database/static-creds/*" {
          capabilities = ["read"]
        }
        path "secret/data/archgate/targets/*" {
          capabilities = ["read"]
        }
        """.formatted(username, target, ttl != null ? ttl : "8h");
    // OpenBao/Vault ACL write: PUT /v1/sys/policies/acl/:name
    putJson("/v1/sys/policies/acl/" + encode(username), Map.of("policy", policy));
    log.debug("[{}] policy {} for target {}", name(), policyName, target);
  }

  @Override
  public void revokeAll(String username) {
    delete("/v1/sys/policies/acl/" + encode(username));
    // A database role/prefix is shared by multiple principals. Without an
    // authoritative principal-to-lease inventory, prefix revocation would
    // disconnect unrelated tenants. Surface incomplete cleanup explicitly.
    throw new IllegalStateException(
        "Policy removed; individual lease revocation requires principal lease inventory");
  }

  private static String encode(String s) {
    return s.replaceAll("[^a-zA-Z0-9._-]", "_");
  }
}
